// Regenerates js/catalog-data.js: the 100 largest coins (CoinGecko) and, for
// each, whether Coinbase lists a USD market whose price really matches.
//
//   node tools/build-catalog.mjs
//
// The price check matters: tickers are not unique, so a coin is only mapped to
// a Coinbase product when both sources agree on the price within 3 %.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'js', 'catalog-data.js');
const sleep = ms => new Promise(r => setTimeout(r, ms));
const get = async url => {
  const r = await fetch(url, { headers: { 'User-Agent': 'portfolio-catalog-build' } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return r.json();
};

const coins = await get('https://api.coingecko.com/api/v3/coins/markets?vs_currency=usd&order=market_cap_desc&per_page=100&page=1');
const products = await get('https://api.exchange.coinbase.com/products');
const usd = new Set(products.filter(p => p.quote_currency === 'USD' && p.status === 'online' && !p.trading_disabled).map(p => p.base_currency));

const rows = [];
for (const c of coins) {
  const sym = c.symbol.toUpperCase();
  let onCoinbase = 0;
  if (usd.has(sym)) {
    try {
      const t = await get(`https://api.exchange.coinbase.com/products/${sym}-USD/ticker`);
      if (Math.abs(Number(t.price) - c.current_price) / c.current_price < 0.03) onCoinbase = 1;
      else console.log('price mismatch, not mapped:', sym, c.id);
    } catch (e) { console.log('skipped', sym, e.message); }
    await sleep(150);
  }
  const img = c.image.split('?')[0].replace('https://coin-images.coingecko.com/coins/images/', '');
  rows.push([c.id, sym, c.name, img, onCoinbase]);
}

fs.writeFileSync(out,
  '// Generated by tools/build-catalog.mjs. [coingeckoId, symbol, name, imagePath, onCoinbase]\n' +
  'export const CRYPTO_TOP = ' + JSON.stringify(rows).replace(/\],\[/g, '],\n[') + ';\n');
console.log(`wrote ${rows.length} coins, ${rows.filter(r => r[4]).length} with live Coinbase prices`);
